-- =========================================
-- TABLA DE UBICACIONES (SEGUIMIENTO)
-- =========================================

CREATE TABLE ubicaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repartidor_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL,
    latitud NUMERIC(10, 7) NOT NULL,
    longitud NUMERIC(10, 7) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ubicaciones_repartidores
        FOREIGN KEY (repartidor_id)
        REFERENCES repartidores(id),

    CONSTRAINT fk_ubicaciones_pedidos
        FOREIGN KEY (pedido_id)
        REFERENCES pedidos(id),

    CONSTRAINT chk_ubicaciones_latitud
        CHECK (latitud >= -90 AND latitud <= 90),

    CONSTRAINT chk_ubicaciones_longitud
        CHECK (longitud >= -180 AND longitud <= 180)
);

CREATE INDEX idx_ubicaciones_repartidor
    ON ubicaciones(repartidor_id);

CREATE INDEX idx_ubicaciones_pedido
    ON ubicaciones(pedido_id);

CREATE INDEX idx_ubicaciones_fecha
    ON ubicaciones(fecha_registro);
