-- =========================================
-- TABLA DE PEDIDOS
-- =========================================

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    repartidor_id BIGINT,
    nombre_cliente VARCHAR(100) NOT NULL,
    telefono_cliente VARCHAR(20),
    direccion_entrega VARCHAR(200) NOT NULL,
    referencia_direccion VARCHAR(200),
    descripcion VARCHAR(500),
    importe NUMERIC(12, 2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP,

    CONSTRAINT fk_pedidos_empresas
        FOREIGN KEY (empresa_id)
        REFERENCES empresas(id),

    CONSTRAINT fk_pedidos_repartidores
        FOREIGN KEY (repartidor_id)
        REFERENCES repartidores(id),

    CONSTRAINT chk_pedidos_estado
        CHECK (estado IN (
            'PENDIENTE', 'ACEPTADO', 'PREPARANDO', 'LISTO',
            'EN_CAMINO', 'ENTREGADO', 'CANCELADO', 'RECHAZADO'
        )),

    CONSTRAINT chk_pedidos_importe
        CHECK (importe >= 0)
);

CREATE INDEX idx_pedidos_empresa
    ON pedidos(empresa_id);

CREATE INDEX idx_pedidos_repartidor
    ON pedidos(repartidor_id);

CREATE INDEX idx_pedidos_estado
    ON pedidos(estado);

-- =========================================
-- TABLA DE HISTORIAL DE PEDIDOS
-- =========================================

CREATE TABLE pedidos_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20) NOT NULL,
    usuario_id BIGINT NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion VARCHAR(500),

    CONSTRAINT fk_pedidos_historial_pedidos
        FOREIGN KEY (pedido_id)
        REFERENCES pedidos(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_pedidos_historial_usuarios
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT chk_pedidos_historial_estado_anterior
        CHECK (estado_anterior IS NULL OR estado_anterior IN (
            'PENDIENTE', 'ACEPTADO', 'PREPARANDO', 'LISTO',
            'EN_CAMINO', 'ENTREGADO', 'CANCELADO', 'RECHAZADO'
        )),

    CONSTRAINT chk_pedidos_historial_estado_nuevo
        CHECK (estado_nuevo IN (
            'PENDIENTE', 'ACEPTADO', 'PREPARANDO', 'LISTO',
            'EN_CAMINO', 'ENTREGADO', 'CANCELADO', 'RECHAZADO'
        ))
);

CREATE INDEX idx_pedidos_historial_pedido
    ON pedidos_historial(pedido_id);

CREATE INDEX idx_pedidos_historial_fecha
    ON pedidos_historial(fecha);
