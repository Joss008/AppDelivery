-- =========================================
-- TABLA DE REPARTIDORES
-- =========================================

CREATE TABLE repartidores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    dni VARCHAR(20) NOT NULL,
    telefono VARCHAR(20),
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_repartidores_empresas
        FOREIGN KEY (empresa_id)
        REFERENCES empresas(id),

    CONSTRAINT chk_repartidores_estado
        CHECK (estado IN ('DISPONIBLE', 'OCUPADO', 'INACTIVO'))
);

CREATE UNIQUE INDEX uq_repartidores_empresa_dni
    ON repartidores(empresa_id, dni);

CREATE INDEX idx_repartidores_empresa
    ON repartidores(empresa_id);
